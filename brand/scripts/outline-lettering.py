"""Outline the brand lettering from the shipped font files (authoring step, not part of the build).

Writes brand/src/lettering.json: glyph outlines in font units (y up), one entry per text run, shaped
with HarfBuzz (kerning applied) at a fixed weight of the variable font. The generator turns these
outlines into the wordmark and the product lockups, so no surface depends on an installed font.

Run from the repo root (uv creates a throw-away environment, nothing is installed in the repo):

    uv run --python 3.12 --with fonttools --with brotli --with uharfbuzz python brand/scripts/outline-lettering.py

Re-run only when the font file, a product name or a weight changes; commit the JSON.
"""

from __future__ import annotations

import hashlib
import json
import sys
from io import BytesIO
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.recordingPen import DecomposingRecordingPen, RecordingPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

REPO = Path(__file__).resolve().parents[2]
FONT = REPO / "apps" / "web" / "src" / "app" / "fonts" / "SpaceGroteskVariable.woff2"
OUT = REPO / "brand" / "src" / "lettering.json"

# key -> (text, weight). "brand" is the family name; the rest are product descriptors.
RUNS: dict[str, tuple[str, int]] = {
    "brand": ("MixAI", 700),
    "tv": ("TV", 500),
    "music": ("Music", 500),
    "decks": ("Decks", 500),
    "live": ("Live", 500),
    "studio": ("Studio", 500),
    "keybpm": ("Key & BPM", 500),
    "server": ("Server", 500),
    "connector": ("Connector", 500),
}


def r(v: float) -> float:
    return round(v, 2)


def contours(font: hb.Font, gid: int) -> list[dict]:
    """One entry per closed contour: SVG path data + bounding box (font units, y up)."""
    rec = RecordingPen()
    font.draw_glyph_with_pen(gid, rec)
    out: list[dict] = []
    current: list = []
    for op, args in rec.value:
        current.append((op, args))
        if op in ("closePath", "endPath"):
            svg = SVGPathPen(None, ntos=lambda v: ("%.2f" % v).rstrip("0").rstrip("."))
            bounds = BoundsPen(None)
            for o, a in current:
                getattr(svg, o)(*a)
                getattr(bounds, o)(*a)
            if bounds.bounds:
                out.append({"d": svg.getCommands(), "bbox": [r(v) for v in bounds.bounds]})
            current = []
    return out


def main() -> int:
    raw = FONT.read_bytes()
    tt = TTFont(BytesIO(raw))
    buf = BytesIO()
    tt.flavor = None
    tt.save(buf)
    face = hb.Face(buf.getvalue())
    upem = face.upem
    os2 = tt["OS/2"]
    result = {
        "$comment": "GENERATED by brand/scripts/outline-lettering.py - do not edit. Outlines of Space Grotesk (OFL-1.1), font units, y up.",
        "font": {
            "family": "Space Grotesk",
            "file": FONT.relative_to(REPO).as_posix(),
            "sha256": hashlib.sha256(raw).hexdigest(),
            "licence": "OFL-1.1",
            "unitsPerEm": upem,
            "capHeight": getattr(os2, "sCapHeight", None),
            "xHeight": getattr(os2, "sxHeight", None),
            "ascender": tt["hhea"].ascent,
            "descender": tt["hhea"].descent,
        },
        "runs": {},
    }
    for key, (text, weight) in RUNS.items():
        font = hb.Font(face)
        font.set_variations({"wght": float(weight)})
        b = hb.Buffer()
        b.add_str(text)
        b.guess_segment_properties()
        hb.shape(font, b, {"kern": True, "liga": False})
        x = 0.0
        glyphs = []
        for info, pos in zip(b.glyph_infos, b.glyph_positions):
            ch = text[info.cluster]
            glyphs.append(
                {
                    "char": ch,
                    "x": r(x + pos.x_offset),
                    "advance": r(pos.x_advance),
                    "contours": contours(font, info.codepoint),
                }
            )
            x += pos.x_advance
        result["runs"][key] = {"text": text, "weight": weight, "advance": r(x), "glyphs": glyphs}
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(result, ensure_ascii=False, indent=1) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO).as_posix()}: {len(result['runs'])} runs, upem {upem}, cap {result['font']['capHeight']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
