// Android resource generators (vector drawables, adaptive icons, AnimatedVectorDrawable). Pure functions.
import { LOGO_MOTION } from '../../src/motion.mjs';
import { WORDMARK, geometry } from '../../src/marks.mjs';
import { C, letteringParts, n, scheme } from './draw.mjs';
import { avdAnimator, linePosition } from './motion.mjs';
import * as P from './path.mjs';

const HEAD = `<?xml version="1.0" encoding="utf-8"?>\n<!-- GENERATED by brand/scripts/build.mjs (do not edit). Source: brand/src/marks.mjs -->`;
const ARGB = (hex) => `#FF${hex.slice(1).toUpperCase()}`;

/** Adaptive icon: 108 dp canvas, the 48 grid scaled by 1.25 and centred (content stays inside the 66 dp circle). */
export const ADAPTIVE = { canvas: 108, scale: 1.25, safeRadius: 33 };

/** Farthest point of a symbol (stroke included) from the centre of the adaptive canvas, in dp. */
export function adaptiveReach(id) {
  const geo = geometry(id).master;
  const c = geo.grid / 2;
  let reach = 0;
  for (const l of geo.lines) for (const sub of P.flatten(P.parse(l.d))) for (const [x, y] of sub) reach = Math.max(reach, Math.hypot(x - c, y - c) + geo.w / 2);
  const [cx, cy, r] = geo.dot;
  reach = Math.max(reach, Math.hypot(cx - c, cy - c) + r);
  return reach * ADAPTIVE.scale;
}

function pathEls(id, sch, { names = false, indent = '        ' } = {}) {
  const geo = geometry(id).master;
  const rows = geo.lines.map(
    (l, i) =>
      `${indent}<path${names ? ` android:name="line${i}"` : ''} android:pathData="${l.d}" android:strokeColor="${ARGB(l.role === 'b' ? sch.b : sch.a)}" android:strokeWidth="${geo.w}" android:strokeLineCap="round" android:strokeLineJoin="round" />`,
  );
  const [cx, cy, r] = geo.dot;
  const dot = `<path android:pathData="${P.circlePath(cx, cy, r)}" android:fillColor="${ARGB(sch.dot)}" />`;
  rows.push(names ? `${indent}<group android:name="dot" android:pivotX="${cx}" android:pivotY="${cy}">\n${indent}    ${dot}\n${indent}</group>` : `${indent}${dot}`);
  return rows.join('\n');
}

function adaptiveVector(id, sch, opts) {
  const off = n((ADAPTIVE.canvas - 48 * ADAPTIVE.scale) / 2);
  return (
    `<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="108dp"\n    android:height="108dp"\n    android:viewportWidth="108"\n    android:viewportHeight="108">\n` +
    `    <group${opts?.names ? ' android:name="body"' : ''} android:translateX="${off}" android:translateY="${off}" android:scaleX="${ADAPTIVE.scale}" android:scaleY="${ADAPTIVE.scale}">\n` +
    `${pathEls(id, sch, opts)}\n    </group>\n</vector>`
  );
}

/** Launcher foreground layer (colour). */
export const launcherForeground = (id) => `${HEAD}\n${adaptiveVector(id, scheme(id, 'dark'))}\n`;

/** Themed-icon layer: one colour, the system tints it. */
export const launcherMonochrome = (id) => `${HEAD}\n${adaptiveVector(id, scheme(id, 'dark', '#ffffff'))}\n`;

/** `mipmap-anydpi-v26/ic_launcher.xml`. */
export function adaptiveIcon({ foreground = '@drawable/ic_launcher_foreground', monochrome = '@drawable/ic_launcher_monochrome' } = {}) {
  return (
    `${HEAD}\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n` +
    `    <background android:drawable="@color/brand_tile" />\n    <foreground android:drawable="${foreground}" />\n    <monochrome android:drawable="${monochrome}" />\n</adaptive-icon>\n`
  );
}

/** `res/values/brand.xml`: the fixed identity colours of one app. */
export function brandColors(id) {
  const sch = scheme(id, 'dark');
  const intro = animationMs('intro');
  if (intro > 1000) throw new Error(`${id}: intro lasts ${intro} ms, the Android system splash allows 1000`);
  if (adaptiveReach(id) > ADAPTIVE.safeRadius) throw new Error(`${id}: the glyph reaches ${adaptiveReach(id).toFixed(1)} dp from the centre, the adaptive safe circle is ${ADAPTIVE.safeRadius} dp`);
  return (
    `${HEAD}\n<resources>\n    <color name="brand_tile">${ARGB(C.tile)}</color>\n    <color name="brand_canvas">${ARGB(C.canvas)}</color>\n` +
    `    <color name="brand_product">${ARGB(sch.a)}</color>\n    <color name="brand_signal">${ARGB(sch.dot)}</color>\n` +
    `    <!-- length of drawable/avd_brand_intro (system splash: windowSplashScreenAnimationDuration) -->\n    <integer name="brand_intro_ms">${intro}</integer>\n</resources>\n`
  );
}

/** 24 dp status-bar / notification icon: the glyph in white (the system tints it). */
export function statusIcon(id) {
  const geo = geometry(id).master;
  const k = 24 / geo.grid;
  return (
    `${HEAD}\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="24dp"\n    android:height="24dp"\n    android:viewportWidth="24"\n    android:viewportHeight="24">\n` +
    `    <group android:scaleX="${k}" android:scaleY="${k}">\n${pathEls(id, scheme(id, 'dark', '#ffffff'))}\n    </group>\n</vector>\n`
  );
}

/** Android TV launcher banner, 320 x 180 dp: symbol + outlined name on the tile colour. */
export function tvBanner(id) {
  const lineH = 56; // height of the lockup line in dp
  const k = lineH / 48;
  const { parts, width } = letteringParts(id, { x: 48 + WORDMARK.gap, y: WORDMARK.baseline, cap: WORDMARK.capHeight, mode: 'dark' });
  const total = (48 + WORDMARK.gap + width) * k;
  const fit = Math.min(1, 272 / total); // 24 dp side margins
  const s = k * fit;
  const x = (320 - total * fit) / 2;
  const y = (180 - 48 * s) / 2;
  const letters = parts.map((p) => `        <path android:pathData="${p.d}" android:fillColor="${ARGB(p.fill)}" />`).join('\n');
  return (
    `${HEAD}\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="320dp"\n    android:height="180dp"\n    android:viewportWidth="320"\n    android:viewportHeight="180">\n` +
    `    <path android:pathData="M0,0h320v180h-320z" android:fillColor="${ARGB(C.tile)}" />\n` +
    `    <group android:translateX="${n(x)}" android:translateY="${n(y)}" android:scaleX="${n(s, 5)}" android:scaleY="${n(s, 5)}">\n${pathEls(id, scheme(id, 'dark'))}\n${letters}\n    </group>\n</vector>\n`
  );
}

/** Total play time of an animation in ms (the last, delayed line included). */
export function animationMs(anim) {
  const M = LOGO_MOTION[anim];
  return Math.round(M.duration * (1 + (M.lineSpread ?? 0)));
}

/**
 * Splash / in-app AnimatedVectorDrawable of one animation, on the adaptive 108 dp canvas (the system splash
 * shows the central two thirds). Starts and ends on the static mark.
 */
export function animatedVector(id, anim) {
  const M = LOGO_MOTION[anim];
  const geo = geometry(id).master;
  const dur = M.duration;
  const target = (name, tracks, opts = {}) =>
    Object.keys(tracks).length
      ? `    <target android:name="${name}">\n        <aapt:attr name="android:animation">\n` +
        avdAnimator(tracks, dur, { loop: M.loop, indent: '            ', ...opts }) +
        `\n        </aapt:attr>\n    </target>`
      : '';
  const targets = [];
  geo.lines.forEach((_, i) => {
    const begin = (M.lineSpread ?? 0) * dur * linePosition(i, geo.lines.length);
    const tracks = {};
    if (M.trimStart) tracks.trimPathStart = M.trimStart;
    if (M.lineOpacity) tracks.strokeAlpha = M.lineOpacity;
    targets.push(target(`line${i}`, tracks, { begin }));
  });
  if (M.dotScale) targets.push(target('dot', { scaleX: M.dotScale, scaleY: M.dotScale }));
  if (M.shakeX) {
    const off = (ADAPTIVE.canvas - 48 * ADAPTIVE.scale) / 2;
    targets.push(target('body', { translateX: M.shakeX }, { map: (v) => off + v * ADAPTIVE.scale }));
  }
  const vector = adaptiveVector(id, scheme(id, 'dark'), { names: true, indent: '                ' })
    .split('\n')
    .map((l) => `        ${l}`)
    .join('\n');
  return (
    `${HEAD}\n<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"\n    xmlns:aapt="http://schemas.android.com/aapt">\n` +
    `    <aapt:attr name="android:drawable">\n${vector}\n    </aapt:attr>\n${targets.filter(Boolean).join('\n')}\n</animated-vector>\n`
  );
}
