// Outputs for web-technology surfaces: the generated data module of @mmo/ui and inline snippets for plain HTML.
import { IDS, WORDMARK, geometry } from '../../src/marks.mjs';
import { LOGO_MOTION } from '../../src/motion.mjs';
import { C, LETTERING, PRODUCTS, esc, letteringParts, n, nameOf } from './draw.mjs';
import { animatedMarkup, logoCss, markPaintCss } from './motion.mjs';
import * as P from './path.mjs';

/** `packages/ui/src/brand/generated/marks.ts`: geometry + outlined lettering for the React components. */
export function uiData() {
  const geo = (g) => `{ grid: ${g.grid}, w: ${g.w}, lines: [${g.lines.map((l) => `{ d: ${JSON.stringify(l.d)}, b: ${l.role === 'b'} }`).join(', ')}], dot: [${g.dot.join(', ')}] }`;
  const marks = IDS.map((id) => `  ${id}: { master: ${geo(geometry(id).master)}, micro: ${geo(geometry(id).micro)} },`).join('\n');
  // Outlined glyphs, deduplicated by weight + character; font units, y down, baseline at y = 0.
  const glyphs = new Map();
  const runs = {};
  for (const [key, run] of Object.entries(LETTERING.runs)) {
    runs[key] = {
      advance: run.advance,
      glyphs: run.glyphs
        .filter((g) => g.contours.length)
        .map((g) => {
          const id = `${run.weight}${g.char}`;
          if (!glyphs.has(id)) {
            const contours = key === 'brand' && g.char === 'i' ? g.contours.slice(0, 1) : g.contours;
            glyphs.set(id, contours.map((c) => P.format(P.mapPoints(P.parse(c.d), (x, y) => [x, -y]), 1)).join(''));
          }
          return [id, g.x];
        }),
    };
  }
  const names = IDS.map((id) => `  ${id}: ${JSON.stringify(nameOf(id))},`).join('\n');
  return `// GENERATED by brand/scripts/build.mjs from brand/src (marks.mjs, motion.mjs, lettering.json). Do not edit.

export type BrandId = ${IDS.map((id) => `"${id}"`).join(' | ')};

export interface BrandGeometry {
  grid: number;
  /** stroke width in grid units */
  w: number;
  /** \`b\` = second stream (parent mark only) */
  lines: ReadonlyArray<{ d: string; b: boolean }>;
  /** the signal dot: cx, cy, r */
  dot: readonly [number, number, number];
}

export const BRAND_IDS: readonly BrandId[] = ${JSON.stringify(IDS)};

export const BRAND_NAMES: Record<BrandId, string> = {
${names}
};

/** master = above 16 px, micro = drawn for 16 px and below. */
export const BRAND_MARKS: Record<BrandId, { master: BrandGeometry; micro: BrandGeometry }> = {
${marks}
};

/** Outlined Space Grotesk glyphs (OFL-1.1): font units (${LETTERING.font.unitsPerEm} per em), y down, baseline y = 0. Key = weight + character. */
export const BRAND_GLYPHS: Record<string, string> = ${JSON.stringify(Object.fromEntries(glyphs), null, 2)};

/** Text runs: \`brand\` = "MixAI" (weight 700), the others = the product descriptor (weight 500). */
export const BRAND_RUNS: Record<"brand" | Exclude<BrandId, "mark">, { advance: number; glyphs: ReadonlyArray<readonly [string, number]> }> = ${JSON.stringify(runs)};

/** Lettering metrics in font units; lockup metrics in units of the 48 grid. */
export const BRAND_LETTERING = {
  capHeight: ${LETTERING.font.capHeight},
  /** the signal: replaces the dot of the "i" (x from the start of the run, y above the baseline) */
  iDot: { x: ${LETTERING.runs.brand.glyphs[1].x + WORDMARK.iDot.cx}, y: ${WORDMARK.iDot.cy}, r: ${WORDMARK.iDot.r} },
  /** first glyph index of "AI" inside the brand run */
  accentFrom: 3,
  descriptorGap: ${WORDMARK.descriptorGap},
  lockup: { capHeight: ${WORDMARK.capHeight}, baseline: ${WORDMARK.baseline}, gap: ${WORDMARK.gap} },
} as const;

/** Durations (ms) of the logo animations; the keyframes live in ./logo.css. */
export const BRAND_MOTION_MS = ${JSON.stringify(Object.fromEntries(Object.entries(LOGO_MOTION).map(([k, v]) => [k, v.duration])))} as const;
`;
}

// ── inline snippets for hand-written HTML (regions) ────────────────────────────────────────
// The markup carries no colours: `bootStyle` paints it through the design-token variables (same names as in
// tokens.css), so a page that loads the tokens follows the theme; a page that does not gets the values from
// `bootStyle({ selfContained: true })`.

/** Inline `<svg class="mixai-logo">`: the mark, ready for the logo motion CSS. */
export function inlineLogo(id, px, attrs = '') {
  return `<svg class="mixai-logo" data-product="${id}"${attrs ? ` ${attrs}` : ''} width="${n(px)}" height="${n(px)}" viewBox="0 0 48 48" role="img" aria-label="${esc(nameOf(id))}">${animatedMarkup(id, null)}</svg>`;
}

/** Inline outlined name ("MixAI" + product), `h` px high (cap height = h / 1.5), for use under or next to the mark. */
export function inlineWordmark(id, h) {
  const cap = 100;
  const { parts, width } = letteringParts(id, { x: 0, y: cap * 1.1, cap });
  const letters = parts.map((p) => `<path class="${p.role === 'accent' ? 'mixai-accent' : 'mixai-ink'}" d="${p.d}"/>`).join('');
  return `<svg class="mixai-wordmark" data-product="${id}" width="${n((h * width) / (cap * 1.5), 2)}" height="${n(h)}" viewBox="0 0 ${n(width, 2)} ${cap * 1.5}" role="img" aria-label="${esc(nameOf(id))}">${letters}</svg>`;
}

/**
 * `<style>` for a boot screen (goes in `<head>`): the logo motion CSS, plus (selfContained) the colour
 * variables and a full-window `.mixai-boot` holder for pages whose stylesheet arrives with the app bundle.
 * No `inset` shorthand: TV web engines older than Chromium 87 ignore it.
 */
export function bootStyle(id, { selfContained = false } = {}) {
  const vars = (mode) => {
    const own = id === 'mark' ? `--mark-a: ${C.streamA[mode]}; --mark-b: ${C.streamB[mode]};` : `--product-${id}: ${PRODUCTS[id].hex[mode]};`;
    return `${own} --mark-signal: ${C.signal[mode]}; background: ${mode === 'dark' ? C.canvas : C.canvasLight};`;
  };
  const boot = selfContained
    ? `.mixai-boot { position: fixed; top: 0; right: 0; bottom: 0; left: 0; display: flex; align-items: center; justify-content: center; ${vars('dark')} }\n:root[data-mode="light"] .mixai-boot { ${vars('light')} }\n`
    : '';
  return `<style>\n${logoCss()}${markPaintCss(id)}\n${boot}</style>`;
}
