/** Construction sheet: keyline grid, stroke unit, optical sizes, clear space, lockup metrics. */
export function constructionSvg() {
  const U = 12; // px per grid unit
  const m = MARK.master;
  const gridLines = Array.from({ length: 49 }, (_, i) => {
    const major = i % 6 === 0;
    const a = `stroke="#ffffff" stroke-opacity="${major ? 0.22 : 0.07}" stroke-width="${major ? 1 : 0.5}"`;
    return `<line x1="${i * U}" y1="0" x2="${i * U}" y2="${48 * U}" ${a}/><line x1="0" y1="${i * U}" x2="${48 * U}" y2="${i * U}" ${a}/>`;
  }).join('');
  const centre = m.lines.map((l) => `<path d="${l.d}" fill="none" stroke="#ffffff" stroke-width="0.12" stroke-dasharray="0.5 0.5"/>`).join('');
  const note = (x, y, t, anchor = 'start') => `<text x="${x}" y="${y}" fill="#b9b5c9" font-family="ui-monospace,Consolas,monospace" font-size="12" text-anchor="${anchor}">${t}</text>`;
  const master = `<g transform="translate(40 60)"><rect width="${48 * U}" height="${48 * U}" fill="${C.tile}"/>${gridLines}` +
    `<rect x="${6 * U}" y="${6 * U}" width="${36 * U}" height="${36 * U}" fill="none" stroke="${C.streamB.dark}" stroke-opacity="0.6" stroke-dasharray="4 4"/>` +
    `<g transform="scale(${U})">${D.inner('mark', 512, D.scheme('mark')).markup}${centre}<circle cx="24" cy="31" r="0.25" fill="${C.canvas}"/></g></g>` +
    note(40, 44, 'MASTER  grid 48 u, live area 36 u (6 u margin), stroke 6 u, round caps and joins') +
    note(40, 60 + 48 * U + 20, `stems x = 9 and 39 (centre lines)   apex y = 9   diagonals end 4.5 u from the dot   dot centre (24, 31), r 4.5 u`) +
    note(40, 60 + 48 * U + 38, 'stroke : gap to the dot = 6 : 4.5 (1 : 0.75)   dot diameter 9 u = 1.5 x stroke   clear space = 12 u (a quarter of the grid) on every side');
  const X = 40 + 48 * U + 48;
  const sizes = [[16, 'micro: own drawing on a 16 grid, stroke 2 px, centre lines on whole pixels'], [24, 'small: master geometry, stroke x 1.12, dot x 1.06'], [32, 'small'], [48, 'master'], [96, 'master']];
  let y = 60;
  const optical = sizes
    .map(([px, label]) => {
      const row = `<g transform="translate(${X} ${y})"><rect width="${px}" height="${px}" fill="${C.tile}"/>${D.place('mark', 0, 0, px)}</g>` + note(X + 112, y + Math.max(14, px / 2 + 4), `${px} px  ${label}`);
      y += Math.max(px, 20) + 18;
      return row;
    })
    .join('');
  const tileY = y + 18;
  const tile = `<g transform="translate(${X} ${tileY})">${[128, 64, 32, 16].map((px, i) => `<g transform="translate(${[0, 148, 232, 284][i]} 0)"><rect width="${px}" height="${px}" rx="${n(px * TILE.radius)}" fill="${C.tile}" stroke="#ffffff" stroke-opacity="0.15"/>${(() => {
    const k = px <= 16 ? TILE.scale.micro : px <= 32 ? TILE.scale.small : TILE.scale.large;
    return D.place('mark', (px * (1 - k)) / 2, (px * (1 - k)) / 2, px * k);
  })()}</g>`).join('')}</g>` + note(X, tileY - 8, `TILE  radius ${TILE.radius * 100} % of the side; symbol ${TILE.scale.large * 100} % (above 32 px), ${TILE.scale.small * 100} % (17 to 32), 100 % (16)`);
  const lockY = tileY + 128 + 56;
  const lock = D.placeLockup('mark', X, lockY, 72);
  const lockNotes = note(X, lockY - 10, `LOCKUP  cap height ${WORDMARK.capHeight} u (half the grid, two thirds of the live area), baseline y = ${WORDMARK.baseline} u, gap ${WORDMARK.gap} u; the dot of the i is the signal`) +
    `<line x1="${X}" y1="${lockY + (WORDMARK.baseline * 72) / 48}" x2="${X + lock.width}" y2="${lockY + (WORDMARK.baseline * 72) / 48}" stroke="${C.streamB.dark}" stroke-opacity="0.6" stroke-dasharray="4 4"/>` +
    `<line x1="${X}" y1="${lockY + ((WORDMARK.baseline - WORDMARK.capHeight) * 72) / 48}" x2="${X + lock.width}" y2="${lockY + ((WORDMARK.baseline - WORDMARK.capHeight) * 72) / 48}" stroke="${C.streamB.dark}" stroke-opacity="0.6" stroke-dasharray="4 4"/>`;
  const famY = lockY + 72 + 60;
  const fam = IDS.slice(1)
    .map((id, i) => `<g transform="translate(${X + (i % 4) * 150} ${famY + Math.floor(i / 4) * 96})">${D.place(id, 0, 0, 56)}${note(0, 76, label(id))}</g>`)
    .join('');
  const famNote = note(X, famY - 12, `PRODUCT GLYPHS  same grid, stroke ${geometry('tv').master.w} u, lines = sources, exactly one dot = signal`);
  const W = X + 640;
  const H = 60 + 48 * U + 60;
  return D.svg(W, H, `0 0 ${W} ${H}`, `<rect width="${W}" height="${H}" fill="${C.canvas}"/>${master}${optical}${tile}${lockNotes}${lock.markup}${famNote}${fam}`, 'MixAI mark construction');
}
