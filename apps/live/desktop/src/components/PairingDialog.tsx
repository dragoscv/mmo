/** Pairing: controller/performer/viewer URLs as QR codes (SVG from Rust) + "allow phones on the network". */
import { useEffect, useState } from "react";
import { motion } from "motion/react";
import { Copy } from "lucide-react";
import { Button, Dialog, DialogContent, DialogDescription, DialogHeader, DialogTitle, Switch } from "@mmo/ui";
import { useT } from "../i18n";
import { api } from "../lib/tauri";
import { useStore } from "../store";

type RoleKey = "controller" | "performer" | "viewer";

function QrCard({ role, url, index }: { role: RoleKey; url: string; index: number }) {
    const t = useT();
    const notify = useStore((s) => s.notify);
    const [svg, setSvg] = useState<string | null>(null);
    useEffect(() => {
        let cancelled = false;
        api.pairingQr(url)
            .then((s) => !cancelled && setSvg(s))
            .catch(() => !cancelled && setSvg(null));
        return () => {
            cancelled = true;
        };
    }, [url]);
    return (
        <motion.figure
            initial={{ opacity: 0, y: 12 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ delay: index * 0.06, type: "spring", stiffness: 300, damping: 30 }}
            className="flex flex-col items-center gap-2 rounded-xl border bg-card p-4"
        >
            {/* SVG is generated by our own Rust command from a validated URL (qrcode crate, no user markup). */}
            <div
                role="img"
                aria-label={`${t(`pair.${role}`)} QR`}
                className="size-44 rounded-lg bg-background p-2 text-foreground [&>svg]:size-full"
                dangerouslySetInnerHTML={svg ? { __html: svg } : undefined}
            />
            <figcaption className="text-center">
                <div className="font-semibold">{t(`pair.${role}`)}</div>
                <div className="text-xs text-muted-foreground">{t(`pair.${role}Hint`)}</div>
            </figcaption>
            <Button
                variant="ghost"
                size="sm"
                onClick={() => {
                    void navigator.clipboard?.writeText(url).then(() => notify("success", "pair.copied"));
                }}
            >
                <Copy /> {t("pair.copy")}
            </Button>
        </motion.figure>
    );
}

export function PairingDialog() {
    const t = useT();
    const open = useStore((s) => s.panel === "pair");
    const openPanel = useStore((s) => s.openPanel);
    const start = useStore((s) => s.start);
    const lan = useStore((s) => s.settings.lan);
    const status = useStore((s) => s.status);
    const setLan = useStore((s) => s.setLan);
    const live = !!start?.lan;

    return (
        <Dialog open={open} onOpenChange={(o) => openPanel(o ? "pair" : null)}>
            <DialogContent size="xl">
                <DialogHeader>
                    <DialogTitle>{t("pair.title")}</DialogTitle>
                    <DialogDescription>{t("pair.body")}</DialogDescription>
                </DialogHeader>
                <div className="flex items-start gap-3 rounded-xl border p-3">
                    <Switch id="pair-lan" checked={lan} disabled={status === "starting"} onCheckedChange={(on) => void setLan(on)} />
                    <label htmlFor="pair-lan" className="flex flex-col gap-0.5">
                        <span className="text-sm font-medium">{t("pair.lan")}</span>
                        <span className="text-xs text-muted-foreground">{t("pair.lanHint")}</span>
                    </label>
                </div>
                {live && start ? (
                    <div className="grid grid-cols-1 gap-3 sm:grid-cols-3">
                        <QrCard role="performer" url={start.performerUrl} index={0} />
                        <QrCard role="controller" url={start.controllerUrl} index={1} />
                        <QrCard role="viewer" url={start.viewerUrl} index={2} />
                    </div>
                ) : (
                    <p className="rounded-xl bg-muted/50 p-4 text-sm text-muted-foreground">{t("pair.localOnly")}</p>
                )}
            </DialogContent>
        </Dialog>
    );
}
