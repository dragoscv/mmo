package ro.mixai.tv

import android.content.Context
import android.media.AudioAttributes
import android.media.AudioManager
import android.media.MediaPlayer
import android.util.Log
import java.util.concurrent.atomic.AtomicBoolean

/**
 * One start per process: the first [take] answers [enabled], every later call answers false, also when the
 * first one was refused. So a setting turned on later, or the root composing again (language change), never
 * plays the sound in the middle of a session.
 */
internal class StartGate {
    private val used = AtomicBoolean(false)

    fun take(enabled: Boolean): Boolean = used.compareAndSet(false, true) && enabled
}

/** Brand signature (ADR-0016): `res/raw/brand_signature.wav`, generated by `brand/scripts/build.mjs`. */
object BrandSound {
    private const val TAG = "BrandSound"
    private val gate = StartGate()

    /** Held while the sound plays: a player nobody references is collected and stops mid-sound. */
    private var playing: MediaPlayer? = null

    private fun done(player: MediaPlayer) {
        player.release()
        if (playing === player) playing = null
    }

    /**
     * Plays the signature once per cold start, on the media stream at the volume the TV is set to.
     * Returns at once: the player is prepared off the main thread and frees itself when the sound ends.
     * Stays silent when [enabled] is false or when something else is already playing. Call on the main thread.
     */
    fun playAtStart(context: Context, enabled: Boolean) {
        if (!gate.take(enabled)) return
        val app = context.applicationContext
        if (app.getSystemService(AudioManager::class.java)?.isMusicActive == true) return
        val player = MediaPlayer()
        playing = player
        try {
            player.setAudioAttributes(
                AudioAttributes.Builder()
                    .setUsage(AudioAttributes.USAGE_MEDIA)
                    .setContentType(AudioAttributes.CONTENT_TYPE_SONIFICATION)
                    .build(),
            )
            app.resources.openRawResourceFd(R.raw.brand_signature).use { player.setDataSource(it) }
            player.setOnPreparedListener { it.start() }
            player.setOnCompletionListener { done(it) }
            player.setOnErrorListener { mp, what, extra ->
                Log.w(TAG, "signature playback error $what/$extra")
                done(mp)
                true
            }
            player.prepareAsync()
        } catch (e: Exception) {
            Log.w(TAG, "signature not played: ${e.message}")
            done(player)
        }
    }
}
