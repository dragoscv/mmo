//! # decks-mapping — MixAI Decks controller mapping engine (ADR-0014, WP19-12)
//!
//! Pure-Rust, permissively licensed building blocks that turn raw controller bytes into a fixed
//! action vocabulary and engine state back into LED / meter feedback:
//!
//! * [`format`] — mapping format v1 (JSON, serde) with a JSON Schema emitted by `schemars`
//!   ([`json_schema_string`]); device match by name regex, USB ids and SysEx identity reply.
//! * [`action`] — the action vocabulary ([`Action`], [`DeckAction`], [`MixerAction`],
//!   [`FxAction`], [`LibraryAction`], [`SamplerAction`], [`ClockAction`]).
//! * [`engine`] — [`MappingEngine::on_midi`] / [`MappingEngine::feedback`], shift and
//!   deck-switching layers, 14-bit CC / NRPN combining, relative encoders, jog touch, soft
//!   takeover, MIDI learn.
//! * [`script`] — optional per-mapping [`rhai`] scripts in a sandbox (no fs / net / modules,
//!   operation-count and wall-time limits).
//! * [`clock`] — MIDI clock generator and follower, timestamp-driven (no threads).
//! * [`groove`] — groove lane: quantised recording of incoming notes into a pattern + playback.
//! * [`ble`] — BLE-MIDI packet decoder / encoder (timestamps, running status, SysEx spanning).
//! * [`transport`] — [`transport::MidiTransport`] trait, in-memory transport, midir backend
//!   behind the `midir` feature.
//! * [`profiles`] — built-in profiles: Pioneer DDJ-FLX4 (rekordbox and Serato), Novation
//!   Circuit Tracks, generic MIDI keyboard, generic 2-deck fallback.
//!
//! Mappings are derived only from manufacturers' published MIDI documentation (see
//! `docs/decks/mapping-format.md`); no GPL mapping data is used.
