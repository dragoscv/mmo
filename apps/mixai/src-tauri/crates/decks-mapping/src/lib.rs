/// JSON Schema (draft 2020-12, generated by `schemars`) of mapping format v1, as a canonical
/// pretty-printed string with sorted object keys (stable regardless of serde_json features).
pub fn json_schema_string() -> String {
    let schema = schemars::schema_for!(format::MappingFile);
    let value = serde_json::to_value(&schema).expect("schema serialises");
    let mut text = serde_json::to_string_pretty(&canonical(value)).expect("schema prints");
    text.push('\n');
    text
}

/// Rebuild every object with its keys inserted in sorted order, so the printed schema does not
/// depend on whether `serde_json/preserve_order` is enabled elsewhere in the workspace.
fn canonical(value: serde_json::Value) -> serde_json::Value {
    match value {
        serde_json::Value::Object(map) => {
            let mut entries: Vec<(String, serde_json::Value)> = map.into_iter().collect();
            entries.sort_by(|a, b| a.0.cmp(&b.0));
            let mut out = serde_json::Map::new();
            for (k, v) in entries {
                out.insert(k, canonical(v));
            }
            serde_json::Value::Object(out)
        }
        serde_json::Value::Array(items) => {
            serde_json::Value::Array(items.into_iter().map(canonical).collect())
        }
        other => other,
    }
}
