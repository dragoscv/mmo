    // ───────── Intro fingerprint ─────────
    // Computes a coarse audio fingerprint of the first 90s of a file
    // (downsampled PCM averaged into 1s buckets, base64-encoded). Two
    // fingerprints from the same show typically share a long substring
    // when they cover the same intro music.
    const fpCache = new Map<string, string>();
    r.get("/intro/fingerprint/:fileId", authMiddleware, async (req, res) => {
        const abs = resolveFileId(req.params.fileId);
        if (!abs || !fs.existsSync(abs)) { res.status(404).json({ error: "file not found" }); return; }
        if (!FFMPEG_BIN) { res.status(503).json({ error: "ffmpeg unavailable" }); return; }
        const cached = fpCache.get(req.params.fileId);
        if (cached) { res.json({ ok: true, fingerprint: cached, durationSec: 90 }); return; }
        try {
            // Extract first 90s as mono 8kHz s16le PCM → average per second → 1 byte each.
            const args = ["-hide_banner", "-loglevel", "error", "-i", abs,
                "-t", "90", "-ac", "1", "-ar", "8000", "-f", "s16le", "-acodec", "pcm_s16le", "pipe:1"];
            const chunks: Buffer[] = [];
            await new Promise<void>((resolve, reject) => {
                const child = spawn(FFMPEG_BIN, args, { windowsHide: true });
                child.stdout.on("data", (b) => chunks.push(b));
                child.on("close", (code) => code === 0 ? resolve() : reject(new Error(`ffmpeg exit ${code}`)));
                child.on("error", reject);
            });
            const pcm = Buffer.concat(chunks);
            const samplesPerSec = 8000;
            const seconds = Math.floor(pcm.length / 2 / samplesPerSec);
            const buckets = new Uint8Array(seconds);
            for (let s = 0; s < seconds; s++) {
                let sum = 0;
                const start = s * samplesPerSec * 2;
                for (let i = 0; i < samplesPerSec; i++) {
                    const v = pcm.readInt16LE(start + i * 2);
                    sum += Math.abs(v);
                }
                buckets[s] = Math.min(255, Math.floor(sum / samplesPerSec / 128));
            }
            const fp = Buffer.from(buckets).toString("base64");
            fpCache.set(req.params.fileId, fp);
            res.json({ ok: true, fingerprint: fp, durationSec: seconds });
        } catch (e) {
            res.status(500).json({ error: e instanceof Error ? e.message : "failed" });
        }
    });

    // POST /video/intro/match — body: { reference: base64, target: base64 }
    // Returns the best alignment offset (in seconds) where the target's
    // intro begins, or null if confidence too low.
    r.post("/intro/match", authMiddleware, express.json(), (req, res) => {
        const body = req.body as { reference?: string; target?: string };
        if (!body.reference || !body.target) { res.status(400).json({ error: "missing fingerprints" }); return; }
        try {
            const ref = Buffer.from(body.reference, "base64");
            const tgt = Buffer.from(body.target, "base64");
            if (ref.length < 10 || tgt.length < 10) { res.json({ ok: true, match: null }); return; }
            // Sliding window correlation: find offset in target where
            // ref best matches (lowest mean absolute difference).
            let bestOffset = 0;
            let bestScore = Infinity;
            const maxOffset = Math.max(0, tgt.length - ref.length);
            for (let off = 0; off <= maxOffset; off++) {
                let sum = 0;
                for (let i = 0; i < ref.length; i++) {
                    sum += Math.abs(ref[i] - tgt[off + i]);
                }
                const avg = sum / ref.length;
                if (avg < bestScore) { bestScore = avg; bestOffset = off; }
            }
            // Confidence: score under 25 = strong match (out of 0..255)
            const confidence = Math.max(0, 1 - bestScore / 80);
            res.json({
                ok: true,
                match: confidence > 0.5 ? { startSec: bestOffset, endSec: bestOffset + ref.length, confidence } : null,
            });
        } catch (e) {
            res.status(500).json({ error: e instanceof Error ? e.message : "match failed" });
        }
    });

