function vttTime(sec: number): string {
    const h = Math.floor(sec / 3600);
    const m = Math.floor((sec % 3600) / 60);
    const s = Math.floor(sec % 60);
    const ms = Math.floor((sec - Math.floor(sec)) * 1000);
    return `${String(h).padStart(2, "0")}:${String(m).padStart(2, "0")}:${String(s).padStart(2, "0")}.${String(ms).padStart(3, "0")}`;
}

async function probeDurationSec(ffprobeBin: string, abs: string): Promise<number | null> {
    return new Promise((resolve) => {
        const child = spawn(ffprobeBin, ["-v", "quiet", "-print_format", "json", "-show_format", abs], { windowsHide: true });
        let stdout = "";
        child.stdout.on("data", (d) => { stdout += d.toString(); });
        child.on("close", () => {
            try {
                const parsed = JSON.parse(stdout) as { format?: { duration?: string } };
                const d = parseFloat(parsed.format?.duration ?? "");
                resolve(Number.isFinite(d) ? d : null);
            } catch { resolve(null); }
        });
        child.on("error", () => resolve(null));
    });
}

async function getThumbsBaseDir(): Promise<string> {
    let baseDir: string;
    try {
        const { app } = await import("electron");
        baseDir = app.getPath("userData");
    } catch {
        baseDir = path.join(process.cwd(), "data");
    }
    const dir = path.join(baseDir, "thumbs");
    if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
    return dir;
}

// ───────── Chromaprint intro detection ─────────

/** Chromaprint default frame period (sec) — fpcalc with stock settings. */
const FP_FRAME_SEC = 0.12379;
/** Fingerprint cache: fileId → raw int32 frame array. */
const fpCache = new Map<string, number[]>();

async function runFpcalc(abs: string, lengthSec: number): Promise<number[] | null> {
    const { FPCALC_BIN } = await import("./ffmpeg-paths");
    if (!FPCALC_BIN) return null;
    return new Promise((resolve) => {
        const child = spawn(FPCALC_BIN, ["-raw", "-length", String(lengthSec), abs], { windowsHide: true });
        let stdout = "";
        child.stdout.on("data", (d) => { stdout += d.toString(); });
        child.on("close", () => {
            const m = stdout.match(/FINGERPRINT=([^\r\n]+)/);
            if (!m) { resolve(null); return; }
            const arr = m[1].split(",").map((s) => parseInt(s, 10)).filter((n) => Number.isFinite(n));
            resolve(arr.length ? arr : null);
        });
        child.on("error", () => resolve(null));
    });
}

function popcount32(n: number): number {
    n = n - ((n >>> 1) & 0x55555555);
    n = (n & 0x33333333) + ((n >>> 2) & 0x33333333);
    return (((n + (n >>> 4)) & 0x0f0f0f0f) * 0x01010101) >>> 24;
}

/** Slide b over a within the first ~120s of frames, find longest run where
 *  per-frame Hamming distance <= maxBitDist. Returns the run translated to
 *  starting frame index in `a`. */
function findLongestCommonRun(a: number[], b: number[], maxBitDist = 12): { aStart: number; length: number } | null {
    const introFrames = Math.min(a.length, b.length, Math.floor(180 / FP_FRAME_SEC)); // search within first 180s
    const minRun = Math.floor(20 / FP_FRAME_SEC); // require >= 20s run
    let best: { aStart: number; length: number } | null = null;
    // Try offsets ±introFrames, step 2 to keep cost manageable
    for (let off = -introFrames; off <= introFrames; off += 2) {
        const aStart0 = Math.max(0, off);
        const bStart0 = Math.max(0, -off);
        const limit = Math.min(a.length - aStart0, b.length - bStart0, introFrames);
        let runStart = -1;
        let runLen = 0;
        for (let i = 0; i < limit; i++) {
            const dist = popcount32((a[aStart0 + i] ^ b[bStart0 + i]) >>> 0);
            if (dist <= maxBitDist) {
                if (runStart < 0) runStart = i;
                runLen++;
                if (runLen >= minRun && (!best || runLen > best.length)) {
                    best = { aStart: aStart0 + runStart, length: runLen };
                }
            } else {
                runStart = -1;
                runLen = 0;
            }
        }
    }
    return best;
}

/** Sibling resolution: same parent dir, same parsed title, different file. */
function findSiblings(currentFileId: string, currentAbs: string): string[] {
    const currentDir = path.dirname(currentAbs).toLowerCase();
    const currentEntry = fileRegistry.get(currentFileId);
    const currentTitle = (currentEntry?.meta as { parsed?: { title?: string } } | undefined)?.parsed?.title?.toLowerCase();
    const out: string[] = [];
    for (const [id, entry] of fileRegistry) {
        if (id === currentFileId) continue;
        if (path.dirname(entry.absPath).toLowerCase() !== currentDir) continue;
        const title = (entry.meta as { parsed?: { title?: string } }).parsed?.title?.toLowerCase();
        if (currentTitle && title && title !== currentTitle) continue;
        out.push(entry.absPath);
        if (out.length >= 2) break;
    }
    return out;
}

/** Find the immediately previous episode (same title, same season, episode-1)
 *  or the last episode of the previous season. Returns absolute path or null. */
function findPreviousEpisode(currentFileId: string, currentAbs: string): string | null {
    const currentDir = path.dirname(currentAbs).toLowerCase();
    const currentEntry = fileRegistry.get(currentFileId);
    const cur = (currentEntry?.meta as { parsed?: { title?: string; season?: number | null; episode?: number | null } } | undefined)?.parsed;
    if (!cur?.title || cur.season == null || cur.episode == null) return null;
    const curTitle = cur.title.toLowerCase();
    let best: { season: number; episode: number; abs: string } | null = null;
    for (const [id, entry] of fileRegistry) {
        if (id === currentFileId) continue;
        if (path.dirname(entry.absPath).toLowerCase() !== currentDir) continue;
        const p = (entry.meta as { parsed?: { title?: string; season?: number | null; episode?: number | null } }).parsed;
        if (!p?.title || p.season == null || p.episode == null) continue;
        if (p.title.toLowerCase() !== curTitle) continue;
        // Must come strictly before current (season, episode) tuple
        if (p.season > cur.season || (p.season === cur.season && p.episode >= cur.episode)) continue;
        if (!best || p.season > best.season || (p.season === best.season && p.episode > best.episode)) {
            best = { season: p.season, episode: p.episode, abs: entry.absPath };
        }
    }
    return best?.abs ?? null;
}

async function getOrComputeFp(fileId: string, abs: string): Promise<number[] | null> {
    const cached = fpCache.get(fileId);
    if (cached) return cached;
    const fp = await runFpcalc(abs, 300);
    if (fp) fpCache.set(fileId, fp);
    return fp;
}

async function detectIntroChromaprint(fileId: string, abs: string): Promise<{ start: number; end: number } | null> {
    const siblings = findSiblings(fileId, abs);
    if (!siblings.length) return null;
    const myFp = await getOrComputeFp(fileId, abs);
    if (!myFp) return null;
    let bestOverall: { start: number; end: number } | null = null;
    for (const sibAbs of siblings) {
        const sibId = `sib-${path.basename(sibAbs)}`;
        const sibFp = await getOrComputeFp(sibId, sibAbs);
        if (!sibFp) continue;
        const run = findLongestCommonRun(myFp, sibFp);
        if (!run) continue;
        const start = run.aStart * FP_FRAME_SEC;
        const end = start + run.length * FP_FRAME_SEC;
        if (start < 0 || end - start < 20) continue;
        if (!bestOverall || (end - start) > (bestOverall.end - bestOverall.start)) {
            bestOverall = { start, end };
        }
    }
    return bestOverall;
}


